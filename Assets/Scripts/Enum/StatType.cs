using UnityEngine;

/// <summary>
/// 属性类型，用于查询与修改角色各项数值。
/// </summary>
public enum StatType
{
    /// <summary>最大生命值。</summary>
    MaxHealth,
    /// <summary>生命回复。</summary>
    HealthRegen,
    /// <summary>力量。</summary>
    Strength,
    /// <summary>敏捷。</summary>
    Agility,
    /// <summary>智力。</summary>
    Intelligence,
    /// <summary>体力。</summary>
    Vitality,
    /// <summary>攻击速度。</summary>
    AttackSpeed,
    /// <summary>伤害。</summary>
    Damage,
    /// <summary>暴击率。</summary>
    CritChange,
    /// <summary>暴击伤害。</summary>
    CritPower,
    /// <summary>护甲穿透。</summary>
    ArmorReduction,
    /// <summary>火焰伤害。</summary>
    FireDamage,
    /// <summary>冰霜伤害。</summary>
    IceDamage,
    /// <summary>闪电伤害。</summary>
    LightningDamage,
    /// <summary>护甲。</summary>
    Armor,
    /// <summary>闪避。</summary>
    Evasion,
    /// <summary>冰霜抗性。</summary>
    IceResistance,
    /// <summary>火焰抗性。</summary>
    FireResistance,
    /// <summary>闪电抗性。</summary>
    LightningResistance
}
